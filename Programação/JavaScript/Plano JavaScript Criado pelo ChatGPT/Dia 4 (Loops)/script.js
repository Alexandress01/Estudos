// Exercícios de Laços de Repetição
let numero = 10;

// Exercício 1: Imprimir os números de 1 a 20 usando um loop for.
for (let num = 1; num <= 20; num++) {
    console.log(`Número: ${num}`);
}

// Exercício 2: Imprimir os números pares de 0 a 20 usando um loop for.
while (numero >= 0) {
    console.log(`O número é: ${numero}`);
    numero--;
}

// Exercício 3: Imprimir os números de 1 a 100 usando um loop for.
for (let numero = 1; numero <= 100; numero++) {
    console.log(`O número é: ${numero}`);
}

// Exercício 4 (extra): Imprimir os números pares de 0 a 20 usando um loop for.
for (let num = 0; num <= 20; num += 2) {
    console.log(`O número par é: ${num}`);
}