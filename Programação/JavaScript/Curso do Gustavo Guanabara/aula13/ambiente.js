// Aula 13 - Laços de Repetição (Parte 1)
// Estrutura de repetição com teste lógico no final
let cont = 1

do {
    console.log(`Passo ${cont}`)
    cont++ // c = c + 1 ou c += 1
} while (cont <= 6)

// Estrutura de repetição com teste lógico no início
while (cont <= 6) {
    console.log(`Passo ${cont}`)
    cont++ // c = c + 1 ou c += 1
}

// Forma burra de exibir algo repetidamente (kkkkkkkkkkkkkkkkkkk)
console.log('Passo 1')
console.log('Passo 2')
console.log('Passo 3')
console.log('Passo 4')
console.log('Passo 5')
console.log('Passo 6')