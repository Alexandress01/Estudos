// Aula 11 - Condições em JavaScript
// Variável para armazenar o país de residência
let pais = 'França'

console.log(`Vivendo em ${pais}`)

// Verifica se o país é Brasil ou outro
if (pais == 'Brasil') { // Condição composta
    console.log('Você é Brasileiro!')
} else {
    console.log('Você é Estrangeiro!')
}